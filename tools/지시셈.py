"""지시가 답을 받았는지 세는 규칙 — 지시읽기·답하기가 같이 쓴다.

두 도구가 따로 세다가 한쪽은 '1건', 다른 쪽은 '16건' 이라고 말한 적이 있다.
셈은 한 군데만 둔다.
"""
import time

묵힘 = 6 * 3600   # 이만큼 지나도록 답이 없으면 '묵은 것' 으로 따로 뺀다


def 밀린것(msgs, 지금=None):
    """→ (밀림, 묵은것) — 답이 안 붙은 지시만 골라 낸다.

    답하기가 '답한때' 를 찍은 지시는 확실히 답한 것이다.
    표가 없는 옛 말은 순서로 짝짓되, 한참 묵은 것은 줄에서 빼 따로 센다.
    묵은 것이 줄에 남아 있으면 뒤에 온 지시까지 밀린 것처럼 보이기 때문이다.
    """
    지금 = 지금 or time.time()
    ms = sorted(msgs or [], key=lambda m: m.get("at", 0))
    줄, 묵은것 = [], []

    def 묵은것빼기(때):
        while 줄 and 때 - 줄[0].get("at", 0) > 묵힘:
            묵은것.append(줄.pop(0))

    for m in ms:
        때 = m.get("at", 0)
        if m.get("who") == "나":
            if m.get("답한때"):
                continue
            묵은것빼기(때)
            줄.append(m)
        else:
            묵은것빼기(때)
            if "맡은수" in m:
                continue      # 새 답 — 맡은 지시에 이미 표를 찍었다
            if 줄:
                줄.pop(0)     # 표가 없는 옛 답 하나가 지시 하나를 맡은 것으로 본다
    묵은것빼기(지금)
    return 줄, 묵은것
